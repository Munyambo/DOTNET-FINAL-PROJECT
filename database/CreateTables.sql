CREATE TABLE UsersR (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    Email NVARCHAR(150) NOT NULL UNIQUE,
    PasswordHash NVARCHAR(200) NOT NULL,
    Role NVARCHAR(20) NOT NULL CHECK (Role IN ('Admin', 'Staff', 'Customer')),
    IsActive BIT NOT NULL DEFAULT 1
);

CREATE TABLE Branches (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    Name NVARCHAR(100) NOT NULL,
    Address NVARCHAR(200) NULL,
    Phone NVARCHAR(20) NULL
);

CREATE TABLE Categories (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    Name NVARCHAR(100) NOT NULL
);

CREATE TABLE Customers (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    FullName NVARCHAR(100) NOT NULL,
    Phone NVARCHAR(20) NULL,
    Address NVARCHAR(200) NULL,
    UserId INT NULL FOREIGN KEY REFERENCES UsersR(Id)
);

CREATE TABLE Staffs (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    FullName NVARCHAR(100) NOT NULL,
    Phone NVARCHAR(20) NULL,
    Position NVARCHAR(50) NULL,
    IsManager BIT NOT NULL DEFAULT 0,
    BranchId INT NOT NULL FOREIGN KEY REFERENCES Branches(Id),
    UserId INT NULL FOREIGN KEY REFERENCES UsersR(Id)
);

CREATE TABLE MenuItems (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    Name NVARCHAR(100) NOT NULL,
    Price DECIMAL(18,2) NOT NULL,
    Description NVARCHAR(500) NULL,
    IsAvailable BIT NOT NULL DEFAULT 1,
    CategoryId INT NOT NULL FOREIGN KEY REFERENCES Categories(Id)
);

CREATE TABLE Orders (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    OrderDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    Status NVARCHAR(20) NOT NULL DEFAULT 'Pending',
    TotalAmount DECIMAL(18,2) NOT NULL,
    CustomerId INT NOT NULL FOREIGN KEY REFERENCES Customers(Id),
    BranchId INT NOT NULL FOREIGN KEY REFERENCES Branches(Id)
);

CREATE TABLE OrderItems (
    Id INT NOT NULL PRIMARY KEY IDENTITY,
    OrderId INT NOT NULL FOREIGN KEY REFERENCES Orders(Id) ON DELETE CASCADE,
    MenuItemId INT NOT NULL FOREIGN KEY REFERENCES MenuItems(Id),
    Quantity INT NOT NULL,
    SpecialInstructions NVARCHAR(300) NULL,
    UnitPrice DECIMAL(18,2) NOT NULL
);